#include "cisco_export.h"

static void sanitize_name(const char *src, char *dst, size_t maxlen) {
    size_t j = 0;
    for (size_t i = 0; src[i] != '\0' && j < maxlen - 1; i++) {
        if (isalnum((unsigned char)src[i])) {
            dst[j++] = src[i];
        } else if (src[i] == ' ' || src[i] == '-' || src[i] == '_') {
            dst[j++] = '_';
        }
    }
    dst[j] = '\0';
}

bool export_cisco_ios_config(const campus_vlsm_t *campus, const char *filepath) {
    if (!campus || !campus->is_valid || !filepath) return false;

    FILE *f = fopen(filepath, "w");
    if (!f) return false;

    fprintf(f, "! ==========================================================================\n");
    fprintf(f, "! CISCO IOS ENTERPRISE CAMPUS SUBNET CONFIGURATION SCRIPT\n");
    fprintf(f, "! Generated by NetLab-Pro Campus Network Subnet Architect\n");
    fprintf(f, "! Date: Computer Networks Lab Project\n");
    fprintf(f, "! ==========================================================================\n");
    fprintf(f, "!\n");
    fprintf(f, "enable\n");
    fprintf(f, "configure terminal\n");
    fprintf(f, "hostname Campus-Core-L3-Switch\n");
    fprintf(f, "ip routing\n");
    fprintf(f, "!\n");

    /* DHCP Excluded Addresses */
    fprintf(f, "! --------------------------------------------------------------------------\n");
    fprintf(f, "! STEP 1: DHCP EXCLUDED ADDRESSES (Gateways & Local Servers)\n");
    fprintf(f, "! --------------------------------------------------------------------------\n");
    for (int i = 0; i < campus->lab_count; i++) {
        const lab_spec_t *lab = &campus->labs[i];
        char gw[16], srv[16];
        ipv4_to_str(lab->gateway_ip, gw, sizeof(gw));
        ipv4_to_str(lab->dns_server_ip, srv, sizeof(srv));
        fprintf(f, "ip dhcp excluded-address %s %s\n", gw, srv);
    }
    fprintf(f, "!\n");

    /* DHCP Pools */
    fprintf(f, "! --------------------------------------------------------------------------\n");
    fprintf(f, "! STEP 2: DYNAMIC HOST CONFIGURATION PROTOCOL (DHCP) SCOPES\n");
    fprintf(f, "! --------------------------------------------------------------------------\n");
    for (int i = 0; i < campus->lab_count; i++) {
        const lab_spec_t *lab = &campus->labs[i];
        char clean_name[MAX_LAB_NAME_LEN];
        sanitize_name(lab->name, clean_name, sizeof(clean_name));

        char net[16], mask[16], gw[16], dns[16];
        ipv4_to_str(lab->network_ip, net, sizeof(net));
        ipv4_to_str(lab->subnet_mask, mask, sizeof(mask));
        ipv4_to_str(lab->gateway_ip, gw, sizeof(gw));
        ipv4_to_str(lab->dns_server_ip, dns, sizeof(dns));

        fprintf(f, "ip dhcp pool POOL_%s\n", clean_name);
        fprintf(f, " network %s %s\n", net, mask);
        fprintf(f, " default-router %s\n", gw);
        fprintf(f, " dns-server %s 8.8.8.8\n", dns);
        fprintf(f, " lease 7 0 0\n");
        fprintf(f, " exit\n");
        fprintf(f, "!\n");
    }

    /* VLAN Definitions */
    fprintf(f, "! --------------------------------------------------------------------------\n");
    fprintf(f, "! STEP 3: VIRTUAL LOCAL AREA NETWORKS (VLANs)\n");
    fprintf(f, "! --------------------------------------------------------------------------\n");
    for (int i = 0; i < campus->lab_count; i++) {
        const lab_spec_t *lab = &campus->labs[i];
        char clean_name[MAX_LAB_NAME_LEN];
        sanitize_name(lab->name, clean_name, sizeof(clean_name));

        fprintf(f, "vlan %d\n", lab->vlan_id);
        fprintf(f, " name %s\n", clean_name);
        fprintf(f, " exit\n");
    }
    fprintf(f, "!\n");

    /* Switch Virtual Interfaces (SVI) / Default Gateways */
    fprintf(f, "! --------------------------------------------------------------------------\n");
    fprintf(f, "! STEP 4: INTER-VLAN ROUTING SWITCH VIRTUAL INTERFACES (SVI)\n");
    fprintf(f, "! --------------------------------------------------------------------------\n");
    for (int i = 0; i < campus->lab_count; i++) {
        const lab_spec_t *lab = &campus->labs[i];
        char gw[16], mask[16];
        ipv4_to_str(lab->gateway_ip, gw, sizeof(gw));
        ipv4_to_str(lab->subnet_mask, mask, sizeof(mask));

        fprintf(f, "interface Vlan%d\n", lab->vlan_id);
        fprintf(f, " description Gateway for %s (%s)\n", lab->name, lab->department);
        fprintf(f, " ip address %s %s\n", gw, mask);
        fprintf(f, " no shutdown\n");
        fprintf(f, " exit\n");
        fprintf(f, "!\n");
    }

    fprintf(f, "! --------------------------------------------------------------------------\n");
    fprintf(f, "! STEP 5: SAVE CONFIGURATION\n");
    fprintf(f, "! --------------------------------------------------------------------------\n");
    fprintf(f, "end\n");
    fprintf(f, "write memory\n");
    fprintf(f, "! [OK] Cisco configuration generated successfully.\n");

    fclose(f);
    return true;
}

bool export_csv_report(const campus_vlsm_t *campus, const char *filepath) {
    if (!campus || !campus->is_valid || !filepath) return false;

    FILE *f = fopen(filepath, "w");
    if (!f) return false;

    fprintf(f, "Lab ID,Lab Name,Department,Workstations,Effective Hosts,VLAN ID,Subnet IP,CIDR,Subnet Mask,First Usable,Last Usable,Default Gateway,Broadcast IP,Block Size,Usable Capacity,Wasted IPs,Efficiency %%\n");

    for (int i = 0; i < campus->lab_count; i++) {
        const lab_spec_t *lab = &campus->labs[i];
        char net[16], mask[16], first[16], last[16], gw[16], bcast[16];
        ipv4_to_str(lab->network_ip, net, sizeof(net));
        ipv4_to_str(lab->subnet_mask, mask, sizeof(mask));
        ipv4_to_str(lab->first_usable, first, sizeof(first));
        ipv4_to_str(lab->last_usable, last, sizeof(last));
        ipv4_to_str(lab->gateway_ip, gw, sizeof(gw));
        ipv4_to_str(lab->broadcast_ip, bcast, sizeof(bcast));

        fprintf(f, "%d,\"%s\",\"%s\",%d,%d,%d,%s,/%d,%s,%s,%s,%s,%s,%u,%u,%u,%.2f\n",
                lab->id, lab->name, lab->department,
                lab->workstations, lab->effective_hosts, lab->vlan_id,
                net, lab->allocated_cidr, mask,
                first, last, gw, bcast,
                lab->block_size, lab->usable_capacity, lab->wasted_ips,
                lab->efficiency_pct);
    }

    fclose(f);
    return true;
}

bool export_summary_text_report(const campus_vlsm_t *campus, const char *filepath) {
    if (!campus || !campus->is_valid || !filepath) return false;

    FILE *f = fopen(filepath, "w");
    if (!f) return false;

    char base_net[16], base_bcast[16], next_free[16];
    ipv4_to_str(campus->base_network_ip, base_net, sizeof(base_net));
    ipv4_to_str(campus->base_broadcast, base_bcast, sizeof(base_bcast));
    ipv4_to_str(campus->next_free_subnet, next_free, sizeof(next_free));

    fprintf(f, "================================================================================\n");
    fprintf(f, "                     CAMPUS SUBNETTING & VLSM DESIGN REPORT                     \n");
    fprintf(f, "================================================================================\n\n");
    fprintf(f, "BASE NETWORK SPECIFICATIONS:\n");
    fprintf(f, "  * Campus Base Network : %s/%d\n", base_net, campus->base_cidr);
    fprintf(f, "  * Broadcast Address   : %s\n", base_bcast);
    fprintf(f, "  * Total Campus Scope  : %llu Addresses\n", (unsigned long long)campus->total_campus_capacity);
    fprintf(f, "  * Total Labs Planned  : %d Labs\n", campus->lab_count);
    fprintf(f, "  * Total Workstations  : %llu Computers\n", (unsigned long long)campus->total_requested_hosts);
    fprintf(f, "  * Total Allocated IPs : %llu Addresses\n", (unsigned long long)campus->total_allocated_blocks);
    fprintf(f, "  * Usable Host Space   : %llu Workstations\n", (unsigned long long)campus->total_usable_hosts);
    fprintf(f, "  * Overall Efficiency  : %.2f %%\n", campus->overall_efficiency);
    fprintf(f, "  * Next Free Subnet    : %s\n", next_free);
    fprintf(f, "  * Free IPs Remaining  : %llu Addresses\n\n", (unsigned long long)campus->free_ips_remaining);

    fprintf(f, "------------------------------------------------------------------------------------------------------------------------------------------------------\n");
    fprintf(f, "%-4s | %-28s | %-6s | %-18s | %-16s | %-32s | %-16s | %-6s\n",
            "ID", "Lab Name", "VLAN", "Subnet Address", "Subnet Mask", "Usable Host Range", "Gateway", "Hosts");
    fprintf(f, "------------------------------------------------------------------------------------------------------------------------------------------------------\n");

    for (int i = 0; i < campus->lab_count; i++) {
        const lab_spec_t *lab = &campus->labs[i];
        char net_cidr[24], mask_str[16], range_str[36], gw_str[16];
        char net[16], first[16], last[16];
        ipv4_to_str(lab->network_ip, net, sizeof(net));
        ipv4_to_str(lab->subnet_mask, mask_str, sizeof(mask_str));
        ipv4_to_str(lab->first_usable, first, sizeof(first));
        ipv4_to_str(lab->last_usable, last, sizeof(last));
        ipv4_to_str(lab->gateway_ip, gw_str, sizeof(gw_str));

        snprintf(net_cidr, sizeof(net_cidr), "%s/%d", net, lab->allocated_cidr);
        snprintf(range_str, sizeof(range_str), "%s -> %s", first, last);

        fprintf(f, "%-4d | %-28.28s | Vlan%-2d | %-18s | %-16s | %-32s | %-16s | %-6u\n",
                lab->id, lab->name, lab->vlan_id, net_cidr, mask_str, range_str, gw_str, lab->usable_capacity);
    }
    fprintf(f, "------------------------------------------------------------------------------------------------------------------------------------------------------\n");

    fclose(f);
    return true;
}
